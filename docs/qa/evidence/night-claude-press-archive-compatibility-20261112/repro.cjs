'use strict';
// Pure public media-packs interface; no worker, Godot, or career simulation.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const os = require('node:os');
const source = process.env.CD_PRESS_REPRO_SOURCE_ROOT;
assert.ok(source, 'CD_PRESS_REPRO_SOURCE_ROOT must point to an isolated git archive of f9c55a92');
const media = require(path.join(source,'native/engine/media-packs.cjs'));
const db = require(path.join(source,'dist/rugby-common-rosters.js'));
const root = process.env.CD_PRESS_REPRO_OUTPUT || fs.mkdtempSync(path.join(os.tmpdir(),'cd-press-quote-interface-'));
fs.mkdirSync(root,{recursive:true});
const profile = path.join(root, 'profile');
fs.mkdirSync(profile, {recursive:true});
const manifest = {schema:'cd-identity-pack-v2',id:'quote-interface-repro',name:'Presse de recette',version:'1',databaseId:db.id,rightsStatus:'test-local',clubs:[],players:[],staff:[],assets:[],press:{journalists:[{id:'presse-0',name:'Journaliste Test Zéro'}]}};
const filename = Buffer.from('pack.json');
const data = Buffer.from(JSON.stringify(manifest));
const local = Buffer.alloc(30), central = Buffer.alloc(46), end = Buffer.alloc(22);
const crc = media.crc32(data);
local.writeUInt32LE(0x04034b50); local.writeUInt16LE(20,4); local.writeUInt16LE(0x800,6); local.writeUInt32LE(crc,14); local.writeUInt32LE(data.length,18); local.writeUInt32LE(data.length,22); local.writeUInt16LE(filename.length,26);
central.writeUInt32LE(0x02014b50); central.writeUInt16LE(20,4); central.writeUInt16LE(20,6); central.writeUInt16LE(0x800,8); central.writeUInt32LE(crc,16); central.writeUInt32LE(data.length,20); central.writeUInt32LE(data.length,24); central.writeUInt16LE(filename.length,28);
end.writeUInt32LE(0x06054b50); end.writeUInt16LE(1,8); end.writeUInt16LE(1,10); end.writeUInt32LE(central.length+filename.length,12); end.writeUInt32LE(local.length+filename.length+data.length,16);
const zip = path.join(root,'pack.zip');
fs.writeFileSync(zip,Buffer.concat([local,filename,data,central,filename,end]));
const store = media.createStore(profile,db);
const inspected = store.inspect(zip);
const installed = store.install(zip,inspected.digest);
assert.equal(installed.counts.journalists,1);
// Representative public projection input, not an imported/validated career.
const archive = {season:1,week:0,club:0,journalist:{id:'presse-0',name:'Nathan Delcourt',outlet:'Mêlée Hebdo'},question:'Nathan Delcourt vous interroge sur le groupe.',answer:'Je réponds à Nathan Delcourt : le groupe garde ma confiance.'};
const model = {meta:{mode:'common',catalogue:[]},clubLife:{press:{history:[structuredClone(archive)]}}};
const before = JSON.stringify(model);
const sourceArchive = JSON.stringify(archive);
const result = store.project(model,{id:installed.id,digest:installed.digest},'base');
assert.equal(JSON.stringify(model),before,'projection input unchanged');
assert.equal(JSON.stringify(archive),sourceArchive,'source archive unchanged');
assert.equal(result.clubLife.press.history[0].answer,'Je réponds à Journaliste Test Zéro : le groupe garde ma confiance.');
const receipt = {source_sha:'f9c55a92939a4699f08c3bbce78fb69e07d81aee',interface:'media-packs.createStore → inspect → install → project',fixture_scope:'representative projected history; not a validated career or observed stock-bank occurrence',pack_accepted:true,source_archive_unchanged:true,projection_input_unchanged:true,input:archive,output:result.clubLife.press.history[0]};
fs.writeFileSync(path.join(root,'receipt.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt,null,2));
