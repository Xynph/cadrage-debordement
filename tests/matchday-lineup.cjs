'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/matchday-lineup.js','utf8'),t.ctx);
vm.runInContext(fs.readFileSync(__dirname+'/../dist/matchday-center.js','utf8'),t.ctx);
run('start(0)');
const state=run('JSON.stringify(S)'),stored=t.store['bdt-v1'];
const balanced=run("matchday02Proposal('equilibre')");
assert.equal(balanced.sheet.lineup.length,15);
assert.equal(balanced.sheet.bench.length,8);
assert.equal(balanced.errors.length,0,'composition initiale légale');
for(const mode of ['equilibre','fraicheur','performance']){
 const proposed=run("matchday02Proposal('"+mode+"')");
 assert.equal(proposed.errors.length,0,mode+' : 23 postes valides');
 assert.equal(new Set([...proposed.sheet.lineup,...proposed.sheet.bench]).size,23,mode+' : sans doublon');
 assert.ok(proposed.changes.length<=23);
}
assert.equal(run('JSON.stringify(S)'),state,'propositions sans mutation de carrière');
assert.equal(t.store['bdt-v1'],stored,'propositions sans écriture');
run("nav('tactics')");
assert.match(t.app.innerHTML,/Assistant de composition/,'assistant intégré dans Préparation');
assert.equal(run('JSON.stringify(S)'),state,'affichage sans mutation');
const previous=run('matchday02Fingerprint()');
run('player(S.lineup[0]).condition=42');
assert.equal(run("matchday02Apply('fraicheur','"+previous+"')"),false,'proposition périmée rejetée');
assert.equal(run('S.lineup.length'),15);
const current=run('matchday02Fingerprint()');
assert.equal(run("matchday02Apply('fraicheur','"+current+"')"),true,'application explicite');
assert.equal(run('sheetErrors().length'),0,'feuille valide après application');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde native');
run('player(S.lineup[0]).injury=2');
const injured=run('S.lineup[0]');
const fresh=run("matchday02Proposal('fraicheur')");
assert.ok(![...fresh.sheet.lineup,...fresh.sheet.bench].includes(injured),'blessé exclu');
assert.equal(run("matchday02Apply('inconnu',matchday02Fingerprint())"),false,'mode inconnu refusé');
run('S.live={finished:false}');
assert.equal(run("matchday02Apply('equilibre',matchday02Fingerprint())"),false,'match en cours protégé');
run('S.live=null;S.phase="ended"');
assert.equal(run("matchday02Proposal('equilibre')"),null,'fin de saison protégée');
console.log('matchday-lineup: PASS (23 postes, modes, non-mutation, empreinte, application et sauvegarde)');
