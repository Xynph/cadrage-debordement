'use strict';
const assert=require('node:assert/strict');
const base=require('../world-data/r1/fr-2026-2027.json');
const alt=require('../world-data/univers01/alternative-2026-2027.json');
const calendar=require('../world-data/univers01/shared-calendar-2026-2027.json');
assert.equal(alt.newCareerStart,'2026-07-01');
assert.equal(calendar.newCareerStart,alt.newCareerStart);
assert.equal(alt.clubs.length,30);
assert.equal(new Set(alt.clubs.map(x=>x.id)).size,30);
assert.deepEqual(alt.clubs.map(x=>x.id).sort(),base.clubs.map(x=>x.id).sort(),'stable R1 IDs, preserves old saves');
assert.deepEqual(alt.competitions.map(x=>x.id).sort(),base.competitions.map(x=>x.id).sort());
assert.equal(alt.clubs.filter(x=>x.competitionId.includes('premiere')).length,14);
assert.equal(alt.clubs.filter(x=>x.competitionId.includes('deuxieme')).length,16);
for(const c of alt.clubs)assert.equal(c.crestAsset,null);
assert.equal(new Set(alt.clubs.map(x=>x.name)).size,30);
assert.deepEqual(calendar.calendarPolicy.worlds,['alternative-original','optional-real-rugby']);
assert.equal(calendar.fixtures.length,0,'do not invent a real match schedule');
assert.ok(calendar.events.every(x=>x.status.startsWith('official')));
assert.equal(calendar.events.find(x=>x.competition==='TOP 14'&&x.type==='final').start,'2027-06-26');
assert.equal(calendar.events.find(x=>x.competition==='PRO D2'&&x.type==='round1').start,'2026-08-27');
console.log(JSON.stringify({passed:true,clubs:30,calendarEvents:calendar.events.length,fixtureClaims:0}));
