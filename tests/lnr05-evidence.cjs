'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
function boot(snapshot){const t=context(snapshot);for(const file of ['lnr-rosters-data.js','lnr-career.js','lnr05-enriched-data.js','lnr05-evidence-center.js'])vm.runInContext(fs.readFileSync(__dirname+'/../dist/'+file,'utf8'),t.ctx);return t}
const fictive=boot();fictive.run('start(0)');
assert.equal(fictive.run('S.lnrMode'),undefined);
assert.equal(fictive.run('lnr05View()'),'','no real dossier in old careers');
assert.ok(fictive.run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'old save unchanged');
const t=boot(),run=t.run;run("start(0,'lnr')");
assert.equal(run('LNR05_EVIDENCE.players.length'),240);
assert.equal(run('new Set(LNR05_EVIDENCE.players.map(p=>p[0])).size'),240);
assert.ok(run('lnr05Enabled()'));
const current=run('JSON.stringify(S)'),storage=t.store['bdt-v1'];
run("nav('team')");
assert.match(t.app.innerHTML,/Cellule LNR · preuves et rotation/);
assert.equal(run('JSON.stringify(S)'),current,'view is read-only');
assert.equal(t.store['bdt-v1'],storage,'view without storage write');
assert.equal(run("lnr05FilterBy('evidence')"),true);
assert.equal(run('JSON.stringify(S)'),current,'filter does not change career');
const proofed=run('club().players.filter(p=>lnr05Proof(p.id)).map(p=>p.id)');
assert.ok(proofed.length>0,'at least one official enrichment in own roster');
const id=proofed[0];
assert.equal(run('lnr05Pick('+JSON.stringify(id)+')'),true);
assert.match(t.app.innerHTML,/Faits LNR/);
assert.equal(run('lnr05Compare('+JSON.stringify(id)+')'),true);
assert.equal(run('compareIds.length'),1);
assert.equal(run('JSON.stringify(S)'),current,'comparison is purely consultative');
const outsider=run('club().players.find(p=>lnr05Proof(p.id)&&lnr05Proposal(p.id)?.valid)?.id||null');
assert.ok(outsider,'at least one eligible enriched reserve');
let preview=run('lnr05Proposal('+JSON.stringify(outsider)+')');
assert.ok(preview.valid&&preview.changes>0&&preview.sheet.lineup.length===15&&preview.sheet.bench.length===8);
assert.equal(run('JSON.stringify(S)'),current,'preview does not mutate');
const stale=preview.token;
run('player('+JSON.stringify(outsider)+').condition=39');
assert.equal(run('lnr05Apply('+JSON.stringify(outsider)+','+JSON.stringify(stale)+')'),false,'refuse stale roster');
preview=run('lnr05Proposal('+JSON.stringify(outsider)+')');
assert.ok(preview.valid,'recomputed preview valid');
assert.equal(run('lnr05Apply('+JSON.stringify(outsider)+','+JSON.stringify(preview.token)+')'),true,'explicit native application');
assert.ok(run('S.lineup.includes('+JSON.stringify(outsider)+')||S.reserves.includes('+JSON.stringify(outsider)+')'));
assert.equal(run('sheetErrors().length'),0);
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'save remains compatible');
const after=run('JSON.stringify(S)');
run('S.live={finished:false}');
assert.equal(run('lnr05Apply('+JSON.stringify(outsider)+',lnr05Token())'),false,'live lock');
run('S.live=null;S.phase="ended"');
assert.equal(run('lnr05Proposal('+JSON.stringify(outsider)+')'),null,'season ended lock');
assert.equal(run('lnr05View().includes("Cellule LNR")'),true,'read-only dossier remains accessible');
console.log('LNR05 EVIDENCE PASS: 240 IDs, legacy, evidence display, preview, stale guard, application and save');
