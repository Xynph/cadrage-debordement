'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/briefing-strategique-v69.js','utf8'),t.ctx);
run('start(0)');
assert.equal(run('v69Selection(matchDossier())'),'neutre');
assert.ok(run('v69BriefingView().includes("Briefing strategique cible")'));
assert.ok(run('v69BriefingView().includes("DECISION DU MANAGER")'));
assert.equal(run('v69Set("invalid",v69Context(matchDossier()))'),false);
assert.equal(run('v69Set("pack","context-perime")'),false);
const token=run('v69Context(matchDossier())');
assert.equal(run('v69Set("pack",'+JSON.stringify(token)+')'),true);
assert.equal(run('v69Selection(matchDossier())'),'pack');
const document=run('createSaveDocument()');
assert.equal(document.state.v69Briefing.plan,'pack');
const parsed=run('parseSaveDocument(JSON.stringify(createSaveDocument()))');
assert.equal(parsed.state.v69Briefing.context,token);
const match=run('createRugbyMatch(nextMatch())');
assert.equal(match.v69Briefing.plan,'pack');
assert.equal(match.v69Briefing.opponent,match.pair[1-match.userSide]);
run('var comparison=S.live;S.live=null');
const packDelta=run('var m=createRugbyMatch(nextMatch());m.tactics[m.userSide]="conquete";tacticalEdge(m,m.userSide)-v69TacticalEdgeBefore(m,m.userSide)');
assert.ok(packDelta>.004&&packDelta<=.03501);
const offDelta=run('m.tactics[m.userSide]="large";tacticalEdge(m,m.userSide)-v69TacticalEdgeBefore(m,m.userSide)');
assert.ok(Math.abs(offDelta+.008)<1e-8);
const otherDelta=run('tacticalEdge(m,1-m.userSide)-v69TacticalEdgeBefore(m,1-m.userSide)');
assert.equal(otherDelta,0);
assert.equal(run('v69Set("couverture",'+JSON.stringify(token)+')'),true);
const cover=run('var c=createRugbyMatch(nextMatch());c.tactics[1-c.userSide]="large";tacticalEdge(c,1-c.userSide)-v69TacticalEdgeBefore(c,1-c.userSide)');
assert.ok(cover<-.004&&cover>=-.03001);
const exchange=run('c.tactics[1-c.userSide]="conquete";tacticalEdge(c,1-c.userSide)-v69TacticalEdgeBefore(c,1-c.userSide)');
assert.ok(Math.abs(exchange-.008)<1e-8);
run('S.live=c');
assert.equal(run('v69Set("pack",'+JSON.stringify(token)+')'),false);
assert.equal(run('v69BriefingView()'),'');
assert.equal(run('c.v69Briefing.plan'),'couverture');
run('S.live=null;S.round++');
assert.equal(run('v69Selection(matchDossier())'),'neutre','aucun report vers le match suivant');
run('delete S.v69Briefing');
assert.equal(run('v69Selection(matchDossier())'),'neutre','ancienne sauvegarde neutre');
const legacy=run('createSaveDocument()');
assert.ok(run('parseSaveDocument('+JSON.stringify(JSON.stringify(legacy))+').state.v69Briefing===undefined'));
assert.equal(run('tacticalEdge(c,c.userSide)'),run('v69TacticalEdgeBefore(c,c.userSide)'));
assert.equal(run('JSON.stringify(S.v69Briefing)'),undefined);
console.log('V69: choix, contexte, moteur, verrouillage, sauvegarde et compatibilite PASS');
