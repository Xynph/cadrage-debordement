'use strict';
const assert=require('node:assert/strict');
const {context}=require('./harness.cjs');
const g=context();
g.run('start(0)');
const state=g.run('JSON.stringify(S)'),disk=JSON.stringify(g.store);
assert.equal(g.run('typeof CDArtDirection'),'object','visual module must be loaded');
const m=g.run('CDArtDirection.snapshot()');
assert.equal(g.run('JSON.stringify(S)'),state,'chart projections must be read-only');
assert.equal(JSON.stringify(g.store),disk,'no write while building charts');
assert.equal(m.squad.length,30);
assert.equal(m.squad[0].attributes.speed,g.run('skill(JSON.parse(JSON.stringify(club().players[0])),"speed")'));
assert.equal(m.needs.length,15);
assert.equal(new Set(m.needs.map(x=>x.slot)).size,15);
assert.equal(m.finance.series[0].value,m.club.cash);
assert.equal(m.finance.series.at(-1).value,g.run('CDFinancePlanning.forecast(careerBudgetModel()).finalBalance'));
assert.equal(m.finance.series.length,g.run('careerBudgetModel().weeks+1'));
assert.equal(m.wages.reduce((s,x)=>s+x.value,0),g.run('totalWages()'));
assert.equal(m.availability.reduce((s,x)=>s+x.value,0),30);
assert.ok(m.candidates.every(p=>!Object.hasOwn(p,'note')&&!Object.hasOwn(p,'potential')&&!Object.hasOwn(p,'skills')),'never reveal unknown candidate ability');
assert.equal(m.next.opponent.id,g.run('S.schedule[0].find(p=>p.includes(S.club)).find(id=>id!==S.club)'));
assert.equal(m.results.length,0,'never invent results on fresh career');
assert.deepEqual(CDArray(g.run('CDArtDirection.extent([-5,2,3])')),[-5,3]);
assert.deepEqual(CDArray(g.run('CDArtDirection.extent([0,0])')),[0,1]);
assert.deepEqual(CDArray(g.run('CDArtDirection.extent([])')),[0,1]);
assert.ok(!/NaN|Infinity/.test(g.run('CDArtDirection.lineChart([{label:"S0",value:0}],"Test",true)')));
assert.ok(!/NaN|Infinity/.test(g.run('CDArtDirection.lineChart([],"Test",true)')));
g.run('club().players[0].name="<img src=x onerror=alert(1)>"');
assert.ok(!g.run('CDArtDirection.scatter(CDArtDirection.snapshot().squad,"age","note")').includes('<img'),'escape labels in charts');
const old=JSON.parse(state);delete old.careerManagement;delete old.worldManagement;
const legacy=context(old);const before=legacy.run('JSON.stringify(S)');legacy.run('CDArtDirection.snapshot()');assert.equal(legacy.run('JSON.stringify(S)'),before);
g.run("S.round=26;S.phase='semi';S.playoff={pairs:[[0,1]]}");
const semi=g.run('CDArtDirection.snapshot()');assert.equal(semi.roundTitle,'Demi-finales');assert.equal(semi.next.neutral,true);assert.equal(semi.next.stadium,'Terrain neutre');
console.log('PASS DA V4: native projections, 15 positions, forecast, payroll, public-only market, old save and SVG edge cases');
function CDArray(x){return JSON.parse(JSON.stringify(x))}
