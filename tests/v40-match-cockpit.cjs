'use strict';
const assert=require('node:assert/strict');
const {context}=require('./harness.cjs');
const main=context(),run=main.run;
run('start(0);beginMatch();pauseMatch();var l=S.live,viewState=matchViewState(l);var selfSide=l.userSide');
assert.equal(run('!!l'),true);
assert.equal(run('!!l.paused'),true);
assert.ok(run('matchCockpitView(viewState).includes("v40-cockpit")'));
assert.ok(run('matchCockpitView(viewState).includes("v40-roster")'));
assert.ok(run('matchCockpitView(viewState).includes("v40-stats")'));
assert.ok(run('matchCockpitView(viewState).includes("v40-tactics")'));
assert.ok(run('matchCockpitView(viewState).includes("match-field")'));
assert.ok(run('matchCockpitView(viewState).includes("Commentaires du match")'));
assert.ok(run('matchCockpitRoster(l,selfSide).includes("Votre effectif en match")'));
assert.ok(run('matchCockpitRoster(l,1-selfSide).includes("Effectif adverse")'));
assert.ok(run('matchCockpitRoster(l,selfSide).includes("Les remplaçants")'));
assert.equal(run('S.live.sheets[selfSide].on.length'),15);
assert.equal(run('S.live.sheets[selfSide].nominated.length'),8);
const saved=run('JSON.stringify(S)'),storage=run('localStorage.getItem("bdt-v1")');
for(let i=0;i<3;i++)run('matchCockpitView(matchViewState(l));matchCockpitMetrics(l);matchCockpitRoster(l,selfSide)');
assert.equal(run('JSON.stringify(S)'),saved,'read-only UI must not mutate match/save');
assert.equal(run('localStorage.getItem("bdt-v1")'),storage);
const p1=context(),p2=context();
p1.run('start(0);beginMatch();pauseMatch();matchCockpitView(matchViewState(S.live))');
p2.run('start(0);beginMatch();pauseMatch()');
assert.equal(p1.run('Math.random()'),p2.run('Math.random()'),'presentation must not consume match RNG');
assert.equal(run('chooseMatchCockpitFocus("analyse")'),true);
assert.equal(run('matchCockpitFocus'),'analyse');
assert.equal(run('chooseMatchCockpitFocus("invalid")'),false);
assert.ok(run('matchCockpitToolbar(l).includes("aria-pressed=\\"true\\"")'));
assert.equal(run('JSON.stringify(S)'),saved,'tabs must not touch saved career');
// Quick substitutions must be based on current legal eligibility, without bypassing rugby rules.
run('var beforeSubs=l.sheets[selfSide].subs;var slot=8;var choices=eligibleChanges(l,selfSide,slot);');
assert.equal(run('matchCockpitRoster(l,selfSide).includes("Remplaçant poste 9")'),true);
if(run('choices.length')>0){
 const id=run('choices[0].id');
 run('substitute(slot,'+JSON.stringify(id)+')');
 assert.equal(run('S.live.sheets[selfSide].subs'),run('beforeSubs')+1);
 assert.equal(run('S.live.sheets[selfSide].on[slot]'),id);
}
run('l.stats[0].possession=60;l.stats[1].possession=40;l.stats[0].territory=35;l.stats[1].territory=65');
assert.ok(run('matchCockpitMetrics(l).includes("60%")'));
assert.ok(run('matchCockpitMetrics(l).includes("35%")'));
assert.ok(run('matchCockpitMetrics(l).includes("Pénalités concédées")'));
assert.ok(run('matchCockpitTactics(l).includes("Plan d’attaque")'));
assert.equal(run('matchCockpitTactics(l).includes("disabled")'),false,'paused tactics should be actionable when replay is complete');
run('l.paused=false');
assert.ok(run('matchCockpitTactics(l).includes("disabled")'));
run('l.paused=true;l.sheets[selfSide].cards.push({id:l.sheets[selfSide].on[0],until:l.minute+10})');
assert.equal(run('matchCockpitCardStatus(l,selfSide,l.sheets[selfSide].on[0])'),'Jaune');
assert.ok(run('matchCockpitRoster(l,selfSide).includes("Jaune")'));
// Legacy save roundtrip and paused match rely solely on existing structures.
const snapshot=JSON.parse(run('JSON.stringify(S)'));
const restored=context(snapshot);
assert.equal(restored.run('!!S.live'),true);
assert.ok(restored.run('matchCockpitView(matchViewState(S.live)).includes("v40-cockpit")'));
assert.equal(restored.run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),true);
console.log(JSON.stringify({passed:true,checks:['5 UI regions','23 and opponents','no state/RNG mutations','tab selection','legal subs','statistics counters','paused tactics','card status','legacy match save']}));
