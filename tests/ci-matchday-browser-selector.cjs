'use strict';
const assert = require('node:assert/strict');
const { SUITES, selectBrowserTests } = require('../ci/matchday-browser-selector.cjs');
const all = [...SUITES];
const check = (paths, expected) => assert.deepEqual(selectBrowserTests(paths), expected, JSON.stringify(paths));
check([], all);
check(['dist/index.html'], all);
check(['dist/game.js'], all);
check(['dist/matchday-center.js'], all);
check(['ci/matchday-browser-selector.cjs'], all);
check(['.github/workflows/matchday-lineup-browser.yml'], all);
check(['tests/matchday-center-browser.py'], [all[0]]);
check(['tests/matchday-lineup-browser.py'], [all[1], all[2]]);
check(['dist/matchday-lineup.js'], [all[1], all[2]]);
check(['tests/matchday-matchplan-browser.py'], [all[2]]);
check(['dist/matchday-matchplan.js'], [all[2]]);
check(['tests/matchday-center-browser.py', 'tests/matchday-matchplan-browser.py'], [all[0], all[2]]);
check(['tests/matchday-lineup-browser.py', 'tests/matchday-center-browser.py'], all);
check(['dist/matchday-matchplan.js', 'docs/nouveau.md'], all);
check(['inconnu-ou-supprime.js'], all);
check([''], all);
assert.deepEqual(selectBrowserTests(null), all);
assert.equal(new Set(all).size, 3);
for (const test of all) assert.match(test, /^tests\/matchday-(center|lineup|matchplan)-browser\.py$/);
