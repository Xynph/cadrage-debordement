'use strict';
const assert=require('node:assert/strict');
const {createUniverse}=require('../modding/r5/universe-contract.cjs');
const base={clubs:[{id:'club:fictional',name:'Club fictif'}],players:[]};
const pack=(id,version='1.0.0',extra={})=>({manifest:{schema:1,id,version,kind:'dataset',...extra},records:{clubs:[{id:'club:'+id,name:'Club '+id}]}});
const world=createUniverse(base);
world.install(pack('world-one'));
assert.deepEqual(world.active(),[]);
assert.equal(world.snapshot().clubs.length,1);
assert.equal(world.select(['world-one']).clubs.length,2);
let save=world.prepareNewCareer({season:1,club:'club:fictional'});
assert.deepEqual(save.modBinding,{schema:1,mods:[{id:'world-one',version:'1.0.0'}]});
assert.equal(world.checkCareer(save).ok,true);
assert.equal(world.checkCareer({season:1}).ok,false);
assert.equal(world.checkCareer({...save,modBinding:{schema:1,mods:[{id:'world-one',version:'2.0.0'}]}}).ok,false);
assert.deepEqual(world.reset(),base);
assert.equal(world.checkCareer({season:1}).ok,true);
assert.equal(world.checkCareer(save).ok,false);
world.install(pack('world-two','1.0.0',{conflicts:['world-one']}));
assert.throws(()=>world.select(['world-one','world-two']),/Conflit/);
assert.deepEqual(world.active(),[]);
const deps=createUniverse(base);deps.install(pack('world-dep','1.0.0',{dependencies:[{id:'world-one',version:'1.0.0'}]}));
assert.throws(()=>deps.select(['world-dep']),/Dépendance/);
assert.throws(()=>world.install(pack('world-one')),/installé/);
assert.throws(()=>world.select(['missing']),/manquant/);
assert.deepEqual(base,{clubs:[{id:'club:fictional',name:'Club fictif'}],players:[]});
console.log(JSON.stringify({passed:true,checks:['opt-in','activation','new career binding','legacy save unchanged','version mismatch','dependency','conflict','reset','base immutable']}));
