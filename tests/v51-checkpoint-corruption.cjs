'use strict';
const assert=require('node:assert/strict');
const {simulate}=require('../dist/world-finance.js');
const clubs=Array.from({length:14},(_,i)=>({id:'c'+i,cash:i<5?800000:i<10?90000:-50000,debt:i>=10?25000:0,reputation:40+i*3,wageRoom:10000,facilities:3,coachConfidence:60}));
const adapters={reputation:({current})=>({next:current}),coachRisk:()=>({risk:0}),facility:({cash,cost})=>({affordable:cash>=cost,remaining:cash-cost}),recruitment:()=>({action:'conserve'}),world:()=>[]};
const profiles=Object.fromEntries(clubs.map((c,i)=>[c.id,{revenue:i<5?260000:i<10?170000:65000,baseCosts:i<5?140000:i<10?175000:280000,investment:25000,repayment:3000}]));
const options={clubs,seed:44,adapters,profiles};
const snapshot=simulate({...options,seasons:5}).checkpoint;
const full=simulate({...options,seasons:15});
assert.deepEqual(simulate({...options,seasons:15,checkpoint:JSON.parse(JSON.stringify(snapshot))}).history,full.history);
const clone=()=>JSON.parse(JSON.stringify(snapshot));
function corrupted(change){const obj=clone();change(obj);assert.throws(()=>simulate({...options,seasons:15,checkpoint:obj}),RangeError);}
corrupted(c=>{c.clubs[1].id=c.clubs[0].id;});
corrupted(c=>{c.history[0].standings[1].clubId=c.history[0].standings[0].clubId;});
corrupted(c=>{c.history[0].standings[1].finish=1;});
corrupted(c=>{c.history[0].standings[0].cash=NaN;});
corrupted(c=>{c.history[0].champion='inconnu';});
corrupted(c=>{c.history[4].standings[0].debt=-1;});
corrupted(c=>{c.clubs[0].cash+=100;});
corrupted(c=>{c.events.push({season:6,clubId:'c0',type:'facility'});});
corrupted(c=>{delete c.penalties.c0;});
corrupted(c=>{c.history[3].awards=null;});
assert.equal(clubs[10].cash,-50000);
console.log('V51: 10 corruptions rejetees et 15 saisons reproductibles');
