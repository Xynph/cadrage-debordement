'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pose}=require('../dist/match3d/premium-motion.js');
const a=Object.freeze({x:10,y:20}),b=Object.freeze({x:20,y:22});
const moving=pose(a,b,.5,120,3);
assert.ok(moving.pace>0&&moving.pace<=1);
assert.ok(Number.isFinite(moving.stride)&&Math.abs(moving.stride)<=1);
assert.ok(Number.isFinite(moving.armSwing)&&Math.abs(moving.armSwing)<=1);
assert.ok(moving.torsoLean>0);
assert.ok(moving.bounce>=0);
assert.equal(moving.kneeBend.length,2);
assert.ok(moving.kneeBend.every(value=>value>=0&&value<=.75));
assert.deepEqual(pose(a,a,.5,120,3).kneeBend,[0,0]);
assert.equal(pose(a,b,1,120,3).stride,0);
assert.equal(pose(a,a,.5,120,3).stride,0);
assert.equal(pose(a,b,.5,120,3).stride,moving.stride);
assert.deepEqual(a,{x:10,y:20});
assert.deepEqual(b,{x:20,y:22});
const distant=pose({x:0,y:0},{x:9999,y:9999},.5,120,3);
assert.ok(distant.pace<=1&&distant.bounce<=.12);
assert.ok(Math.abs(pose(a,b,-5,120,3).stride)<1e-10);
assert.ok(Math.abs(pose(a,b,5,120,3).stride)<1e-10);
const html=fs.readFileSync(path.join(__dirname,'../dist/index.html'),'utf8');
assert.ok(html.indexOf('match3d/premium-motion.js')>0);
assert.ok(html.indexOf('match3d/player-model.js')>0);
assert.ok(html.indexOf('match3d/player-model.js')<html.indexOf('match3d/match3d.js'));
assert.ok(html.indexOf('match3d/premium-motion.js')<html.indexOf('match3d/match3d.js'));
assert.ok(html.includes('match-v61-advisor.js')&&html.includes('media-world-v60.js'));
console.log('MATCH 3D premium motion: 16 checks OK');
