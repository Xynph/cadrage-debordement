'use strict';
const assert=require('node:assert/strict');
const {createRegistry,preparePackage,normalizedManifest,safePath}=require('../modding/r2/runtime.cjs');
const source={clubs:[{id:'club:base',name:'Club fictif'}]};
const pkg=(id,extra={})=>({manifest:{schema:1,id,version:'1.0.0',title:'Pack fictif de test',kind:'combined',baseGame:1,data:[{type:'clubs',path:'data/clubs.json'}],assets:[{type:'club-logo',ownerId:'club:example',path:'images/club.png',bytes:100,sha256:'a'.repeat(64)}],...extra},files:{'data/clubs.json':[{id:'club:'+id,name:'Club test '+id}]}});
for(const path of ['../secret.png','/root/img.png','a//b.png','a\\b.png','https://server/img.png','a/%2e%2e/img.png'])assert.equal(safePath(path),false,path);
assert.equal(safePath('logos/clubs/example.webp'),true);
assert.throws(()=>normalizedManifest({...pkg('example').manifest,version:'bad'}),/version/);
assert.throws(()=>normalizedManifest({...pkg('example').manifest,assets:[{...pkg('example').manifest.assets[0],sha256:'bad'}]}),/SHA/);
assert.throws(()=>preparePackage({...pkg('example'),files:{'data/extra.json':[]}}),/non déclaré/);
const registry=createRegistry(source);
registry.install(pkg('example'));
assert.deepEqual(registry.active(),[]);
assert.deepEqual(registry.activate(['example']).clubs.map(x=>x.id),['club:base','club:example']);
const binding=registry.saveBinding();
assert.equal(registry.checkSave(binding).ok,true);
assert.equal(registry.checkSave({schema:1,mods:[{id:'example',version:'2.0.0'}]}).ok,false);
const another=createRegistry(source);
another.install(pkg('example',{version:'2.0.0'}));
assert.equal(another.checkSave(binding).ok,false);
assert.deepEqual(registry.disable(),source);
assert.deepEqual(registry.active(),[]);
registry.install(pkg('another',{conflicts:['example']}));
assert.throws(()=>registry.activate(['example','another']),/incompatibles/);
assert.deepEqual(registry.active(),[]);
assert.deepEqual(source,{clubs:[{id:'club:base',name:'Club fictif'}]},'base never mutated');
const dependent=createRegistry();
dependent.install(pkg('dependent',{dependencies:[{id:'example',version:'1.0.0'}]}));
assert.throws(()=>dependent.activate(['dependent']),/manquante/);
console.log(JSON.stringify({passed:true,checks:['path traversal','manifest','assets sha','undeclared file','opt-in','conflicts','dependencies','save binding','disable','base isolation']}));
