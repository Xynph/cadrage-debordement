'use strict';
const assert=require('node:assert/strict');
const {annual,recoveryPlan}=require('../dist/financial-recovery.js');
const state={cash:-100000,debt:200000,wageRoom:20000};
const first=annual(state,{revenue:100000,baseCosts:120000,investment:40000,repayment:10000});
assert.equal(first.restriction,'redressement');
assert.equal(first.investmentDeferred,40000);
assert.equal(first.wageCeiling,14000);
assert.equal(first.cash,-105600);
assert.equal(first.debt,208000);
assert.equal(first.canRecruit,false);
assert.equal(state.cash,-100000);
const plan=recoveryPlan(state,15,()=>({revenue:300000,baseCosts:140000,investment:0,repayment:15000}));
assert.equal(plan.history.length,15);
assert.ok(plan.history.some(x=>x.restriction==='normal'));
assert.ok(plan.final.debt>=0);
assert.deepEqual(plan,recoveryPlan(state,15,()=>({revenue:300000,baseCosts:140000,investment:0,repayment:15000})));
const poor=recoveryPlan(state,10,()=>({revenue:10000,baseCosts:500000,investment:0,repayment:0}));
assert.ok(poor.final.cash<0);
assert.ok(poor.history.every(x=>x.restriction==='redressement'));
assert.throws(()=>annual(state,{revenue:-1,baseCosts:2}),RangeError);
assert.throws(()=>recoveryPlan(state,16,()=>({revenue:1,baseCosts:1})),RangeError);
console.log(JSON.stringify({passed:true,checks:['déficit','dette','restriction','arbitrage','redressement 15 saisons','crise prolongée','déterminisme','validation']}));
