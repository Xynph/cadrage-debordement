'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/bureau-agents-v71.js','utf8'),t.ctx);
assert.equal(run('CDAgentsV71.install(globalThis)'),true);
run('start(0)');
run('marketTab="contracts"');
assert.ok(run('contractsPanel().includes("Bureau des agents")'),'panneau ajoute aux contrats');
const id=run('club().players.find(p=>p.contractEnd===S.season)?.id');
assert.ok(id,'joueur a prolonger');
run('var candidate=player('+JSON.stringify(id)+');candidate.dev.retireAge=Math.max(candidate.dev.retireAge,candidate.age+4)');
const bridge='({reservation:reservationWage,fee:contractFee,negotiate:negotiateContract,save:()=>{save();return !lastSaveError;},render:()=>{}})';
const candidate=run('player('+JSON.stringify(id)+')');
const originalSalary=candidate.salary;
const originalEnd=candidate.contractEnd;
const quote=run('CDAgentsV71.quote(S,'+JSON.stringify(id)+',2,"equilibre",'+bridge+')');
assert.ok(quote&&quote.wage>=quote.minimum&&quote.totalCommitment>0,'cotation positive');
assert.ok(quote.end>originalEnd,'prolongation reelle');
assert.equal(quote.deltaWeek,quote.wage-originalSalary);
assert.equal(run('CDAgentsV71.quote(S,"invalid",2,"equilibre",'+bridge+')'),null);
assert.equal(run('CDAgentsV71.quote(S,'+JSON.stringify(id)+',2,"unknown",'+bridge+')'),null);
assert.equal(run('CDAgentsV71.quote(S,'+JSON.stringify(id)+',0,"equilibre",'+bridge+')'),null);
assert.equal(run('CDAgentsV71.perform(S,'+JSON.stringify(id)+',2,"equilibre",'+bridge+')'),true);
assert.equal(run('S.economy.talks[talkKey('+JSON.stringify(id)+',"renew")].status'),'ready');
assert.equal(run('S.v71AgentDesk.history.length'),1);
assert.equal(run('S.v71AgentDesk.history[0].policy'),'equilibre');
assert.equal(run('player('+JSON.stringify(id)+').salary'),originalSalary,'aucun salaire change avant confirmation');
assert.equal(run('S.v71AgentDesk.history[0].status'),'ready');
const copy=run('parseSaveDocument(JSON.stringify(createSaveDocument()))');
assert.equal(copy.state.v71AgentDesk.history.length,1,'mandat sauvegarde');
assert.equal(copy.state.v71AgentDesk.history[0].id,id);
const key=run('talkKey('+JSON.stringify(id)+',"renew")');
assert.equal(run('confirmContract('+JSON.stringify(key)+')'),true);
assert.equal(run('S.v71AgentDesk.history[0].status'),'signed','signature synchronisee');
assert.equal(run('player('+JSON.stringify(id)+').salary'),quote.wage);
assert.equal(run('player('+JSON.stringify(id)+').contractEnd'),quote.end);
assert.equal(run('S.v71AgentDesk.history.length'),1,'pas de doublon apres signature');
assert.equal(run('CDAgentsV71.perform(S,'+JSON.stringify(id)+',2,"ferme",'+bridge+')'),false,'pas de prolongation a echeance inchangee');
run('delete S.v71AgentDesk');
assert.equal(run('parseSaveDocument(JSON.stringify(createSaveDocument())).state.v71AgentDesk===undefined'),true,'ancienne sauvegarde acceptee');
run('S.live={finished:false}');
assert.equal(run('CDAgentsV71.perform(S,'+JSON.stringify(id)+',3,"securiser",'+bridge+')'),false,'aucune offre pendant un match');
run('S.live=null');
assert.equal(run('CDAgentsV71.install(globalThis)'),true,'installation idempotente');
console.log('V71 PASS : bureau, devis, duree, ecriture contrat, signature, import historique et verrou match');
