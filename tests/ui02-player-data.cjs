'use strict';
const assert=require('node:assert/strict');
const {context}=require('./harness.cjs');
const ui=require('../dist/ui02-player-data.js');
const g=context();
g.run('start(0)');
const before=g.run('JSON.stringify(S)'),saved=g.store['bdt-v1'];
const players=JSON.parse(g.run('JSON.stringify(club().players)'));
const ctx={season:g.run('S.season'),lineup:JSON.parse(g.run('JSON.stringify(S.lineup)')),reserves:JSON.parse(g.run('JSON.stringify(S.reserves)'))};
const deps={roleNote:g.run('roleNote'),potentialAtRole:g.run('potentialAtRole'),skill:g.run('skill'),physicalLoadValue:g.run('physicalLoadValue'),attributes:g.run('ATTR')};
assert.ok(players.length>=23);
const p=ui.playerView(players[0],deps,ctx);
assert.equal(p.id,players[0].id);
assert.equal(p.note,g.run('roleNote(club().players[0])'));
assert.equal(p.potential,g.run('potentialAtRole(club().players[0])'));
assert.equal(p.attributes.scrum.value,Math.round(g.run('skill(club().players[0],"scrum")')));
assert.equal(p.physical,g.run('physicalLoadValue(club().players[0])'));
assert.equal(Object.keys(p.attributes).length,Object.keys(deps.attributes).length);
assert.ok(['Titulaire','Banc','Hors groupe','Blessé'].includes(p.status));
const table=ui.tableView(players,deps,ctx);
assert.equal(table.rows.length,players.length);
assert.deepEqual(table.columns.map(x=>x.key),Array.from(ui.PRESETS.overview));
const contracts=ui.tableView(players,deps,ctx,{preset:'contracts',sortBy:'salary',direction:'desc'});
assert.ok(contracts.rows.every((row,i,all)=>i===0||all[i-1].cells.salary>=row.cells.salary));
const custom=ui.tableView(players,deps,ctx,{columns:['name','name','condition'],limit:4});
assert.deepEqual(custom.columns.map(x=>x.key),['name','condition']);
assert.equal(custom.total,players.length);
assert.equal(custom.rows.length,4);
assert.ok(ui.tableView(players,deps,ctx,{search:players[0].name.toUpperCase(),family:players[0].fam}).rows.some(x=>x.id===p.id));
const injured=JSON.parse(JSON.stringify(players));injured[0].injury=2;
assert.ok(ui.tableView(injured,deps,ctx,{onlyInjured:true,columns:['name','status']}).rows.some(x=>x.id===p.id&&x.cells.status==='Blessé'));
assert.equal(ui.tableView(players,deps,ctx,{expiring:true}).total,players.filter(x=>x.contractEnd<=ctx.season).length);
const comp=ui.comparePlayers(players.slice(0,2),deps,ctx);
assert.equal(comp.rows.find(x=>x.key==='note').values[0],p.note);
assert.equal(comp.rows.find(x=>x.key==='scrum').values[0],p.attributes.scrum.value);
assert.throws(()=>ui.tableView(players,deps,ctx,{columns:['__proto__']}),/Colonne/);
assert.throws(()=>ui.tableView(players,deps,ctx,{sortBy:'bad'}),/Tri/);
assert.throws(()=>ui.tableView(players,deps,ctx,{direction:'sideways'}),/Sens/);
assert.throws(()=>ui.comparePlayers([players[0],players[0]],deps,ctx),/différents/);
const legacy=JSON.parse(JSON.stringify(players[0]));delete legacy.skills;delete legacy.dev;
const old=JSON.stringify(legacy),legacyView=ui.playerView(legacy,deps,ctx);
assert.equal(JSON.stringify(legacy),old);
assert.ok(Number.isFinite(legacyView.note)&&Number.isFinite(legacyView.potential));
assert.equal(g.run('JSON.stringify(S)'),before,'UI projection changed the career');
assert.equal(g.store['bdt-v1'],saved,'UI projection wrote a save');
const resume=context(JSON.parse(before));
assert.ok(resume.run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'));
console.log(JSON.stringify({passed:true,checks:['real native skills','role rating','native potential','load','configurable columns','sorting','search','injuries','contracts','comparison','legacy','unchanged career','saved game']}));
