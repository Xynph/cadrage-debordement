'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/squad-health-center.js','utf8'),t.ctx);
run('start(0)');
const initial=run('JSON.stringify(S)');
const data=run('squadHealthSnapshot()');
assert.equal(data.rows.length,run('club().players.length'),'effectif réel');
assert.equal(data.coverage.length,15,'quinze postes de rugby');
assert.equal(Object.values(data.scores).reduce((a,b)=>a+b,0),data.rows.length,'états exclusifs');
assert.equal(run('JSON.stringify(S)'),initial,'modèle ne modifie pas la carrière');
assert.match(run('squadHealthView()'),/Disponibilité et rotation/);
assert.match(run('squadHealthView()'),/setPhysicalTraining/);
assert.match(run('squadHealthView()'),/Composer les 23/);
assert.equal(run('JSON.stringify(S)'),initial,'rendu sans mutation');
run("squadTab='health';nav('team')");
assert.match(t.app.innerHTML,/Centre de disponibilité de l’effectif/,'onglet réellement navigable');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde native intacte');
run('club().players[0].injury=3;club().players[1].condition=55;ensurePhysicalLoad(club().players[2]).fatigue=70');
const stress=run('squadHealthSnapshot()');
assert.ok(stress.scores.injured>=1&&stress.scores.high>=1);
assert.ok(stress.coverage.every(c=>c.available<=c.eligible));
assert.ok(stress.risks.every(c=>c.status!=='covered'));
run('var healthId=club().players[3].id');
assert.equal(run("setPhysicalTraining(healthId,'repos')"),true,'commande native hors match');
assert.equal(run('physicalPlan(player(healthId))'),'repos');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde compatible');
run('S.trained=true');
assert.equal(run("setPhysicalTraining(healthId,'intense')"),false,'pas de modification après séance');
assert.equal(run('squadHealthSnapshot().trainable'),false);
console.log('squad-health-center: PASS (blessures, charge, postes, rotation, plans natifs, sauvegardes)');
