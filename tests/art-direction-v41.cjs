'use strict';
const assert = require('node:assert/strict');
const charts = require('../dist/art-direction-v4.js');
const focusable = /class="da4-chart-viewport" tabindex="0" role="region" aria-label="Graphique défilant horizontalement"/;
const line = charts.lineChart([{label:'S0',value:12},{label:'S1',value:9}],'Projection',true);
assert.match(line,focusable,'financial line chart scroll container is keyboard reachable');
assert.match(line,/role="img"/,'static financial chart retains concise image semantics');
assert.match(line,/Lire les valeurs/,'financial data stays available as a table');
const scatter = charts.scatter([{name:'Joueur test',age:24,note:72,family:2}]);
assert.match(scatter,focusable,'squad scatter scroll container is keyboard reachable');
assert.match(scatter,/role="group" aria-label="Âge et niveau au poste"/,'focused SVG points remain exposed inside a group');
assert.match(scatter,/class="da4-player-point[^"]*"[^>]*tabindex="0" aria-label="Joueur test/,'each player point stays keyboard reachable and named');
assert.match(scatter,/Lire les valeurs/,'player data table remains available');
const market = charts.scatter([{name:'Candidat public',price:1000,salary:200,family:3}],'price','salary','Marché public');
assert.match(market,/role="group" aria-label="Marché public"/);
assert.doesNotMatch(market,/potential|skills|note=/i,'market scatter must not expose hidden ratings');
const academy = charts.potentials([{name:'Espoir test',position:'Pilier',age:19,note:55,potential:78}]);
assert.match(academy,focusable,'academy interval chart scroll container is keyboard reachable');
assert.match(academy,/Lire les valeurs/,'academy data table remains available');
console.log('PASS V4.1: keyboard scrolling regions, SVG points, unchanged data tables and public market');
