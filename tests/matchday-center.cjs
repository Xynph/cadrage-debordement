'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/matchday-center.js','utf8'),t.ctx);
run('start(0)');
const before=run('JSON.stringify(S)'),snapshot=run('matchdayReadiness()');
assert.equal(snapshot.selected,run('starters().length'),'Xv issus de la vraie sélection');
assert.equal(snapshot.substitutes,run('S.reserves.length'),'banc issu de la vraie sélection');
assert.equal(snapshot.depth.length,15,'couverture des quinze postes');
assert.equal(run('JSON.stringify(S)'),before,'briefing sans mutation de carrière');
const html=run('matchdayReadinessView()');
assert.match(html,/Briefing d’avant-match/);
assert.match(html,/Vérifier les 23/);
assert.match(html,/Disponibilité & rotation/);
assert.match(html,/adoptDossierPlan/);
assert.equal(run('JSON.stringify(S)'),before,'rendu sans mutation');
run("nav('tactics')");
assert.match(t.app.innerHTML,/Préparation du prochain match/,'briefing intégré dans Préparation');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde compatible');
run('var topId=S.lineup[0];player(topId).condition=52;ensurePhysicalLoad(player(topId)).fatigue=77');
const risk=run('matchdayReadiness()');
assert.ok(risk.tired.includes(run('topId')),'joueur à charge élevée signalé');
assert.ok(risk.issues.some(x=>x.kind==='tired'),'alerte fatigue présente');
assert.ok(risk.depth.every(x=>x.eligible>=x.fresh),'couverture cohérente');
const frozen=run('JSON.stringify(S)');
run('matchdayReadinessView()');
assert.equal(run('JSON.stringify(S)'),frozen,'pas de mutation pendant comparaison');
run("S.tactic='equilibre';S.defence='equilibre'");
const expected=run('matchDossier()?.advice');
if(expected){run('adoptDossierPlan()');assert.equal(run('S.tactic'),expected.attack);assert.equal(run('S.defence'),expected.defence)}
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde après action native');
run("S.live={finished:false}");
const live=run('matchdayReadiness()');
assert.equal(live.canPrepare,false);
assert.doesNotMatch(run('matchdayReadinessView()'),/adoptDossierPlan/,'pas de décision pendant match');
console.log('matchday-center: PASS (dossier adverse, feuille à 23, fatigue, choix natif et sauvegardes)');
