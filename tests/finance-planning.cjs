'use strict';
const assert=require('node:assert/strict');
const {forecast,compare}=require('../dist/finance-planning.js');
const base={cash:1000000,weeklyIncome:160000,weeklyWages:130000,weeklyOtherCosts:10000,weeks:4};
let f=forecast(base);
assert.equal(f.initialBalance,1000000);
assert.equal(f.weeklyNet,20000);
assert.equal(f.finalBalance,1080000);
assert.deepEqual(f.entries.map(e=>e.balance),[1020000,1040000,1060000,1080000]);
assert.equal(f.salaryShare,130000/160000);
assert.equal(f.firstDeficit,null);
assert.equal(forecast({...base,cash:1000,weeklyWages:200000}).firstDeficit,1);
assert.equal(forecast({...base,cash:-1}).firstDeficit,0);
assert.equal(forecast({...base,weeklyIncome:0,weeklyWages:0}).salaryShare,null);
assert.equal(forecast({...base,oneOffCosts:50000,oneOffIncome:20000}).finalBalance,1050000);
const c=compare(base,[{name:'Recrutement',adjustments:{weeklyWages:140000,oneOffCosts:100000}},{name:'Sponsor',adjustments:{weeklyIncome:170000}}]);
assert.equal(c.scenarios[0].delta,-140000);
assert.equal(c.scenarios[1].delta,40000);
for(const invalid of [{...base,weeks:0},{...base,weeks:105},{...base,weeks:1.5},{...base,weeklyWages:-1},{...base,cash:Infinity},{...base,weeklyIncome:NaN}])assert.throws(()=>forecast(invalid),RangeError);
assert.throws(()=>compare(base,[{name:'x',adjustments:{cash:42}}]),RangeError);
assert.throws(()=>compare(base,[{name:'',adjustments:{}}]),RangeError);
assert.equal(JSON.stringify(base),JSON.stringify({cash:1000000,weeklyIncome:160000,weeklyWages:130000,weeklyOtherCosts:10000,weeks:4}));
console.log(JSON.stringify({passed:true,checks:['prévision hebdomadaire','solde et déficit','recettes et dépenses ponctuelles','part des salaires','comparaison de scénarios','validation des entrées','sans mutation']}));