'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const {context}=require('./harness.cjs');
const root=path.join(__dirname,'..','dist');
const moduleText=fs.readFileSync(path.join(root,'ui-preferences.js'),'utf8');
const source=fs.readFileSync(path.join(root,'game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
assert.ok(html.includes('<script src="ui-preferences.js"></script><script src="game.js"></script>'));
assert.ok(html.includes('<script src="manager-mobility.js"></script>'));
assert.ok(source.includes('ui01Navigation(view,S,r)'));
assert.ok(source.includes('managerMobilityOnSeasonStart()'));
assert.ok(css.includes('ui01-layout'));
assert.ok(css.includes('@media(max-width:800px)'));
assert.ok(css.includes('prefers-reduced-motion'));
const a=context();
let dark=true,change=null;
const rootAttrs={};
a.ctx.document.documentElement={setAttribute(k,v){rootAttrs[k]=v}};
a.ctx.window.matchMedia=query=>{
 assert.equal(query,'(prefers-color-scheme: dark)');
 return {get matches(){return dark},addEventListener(type,fn){assert.equal(type,'change');change=fn}};
};
vm.runInContext(moduleText,a.ctx);
assert.equal(a.run('ui01Pref'),'system');
assert.equal(rootAttrs['data-cd-theme'],'analyste');
assert.ok(a.run('ui01Navigation("dashboard",{clubs:[{abbr:"ABC"}],club:0,season:2},3)').includes('BUREAU'));
const known=['dashboard','team','tactics','plans','staff','recruitment','match','league','history','market','formation','finance','saves','help'];
for(const route of known){
 assert.equal(a.run('UI01_GROUPS.some(g=>g.tabs.some(x=>x[0]==='+JSON.stringify(route)+'))'),true,route);
}
a.run('start(0)');
assert.ok(a.app.innerHTML.includes('ui01-appbar'));
assert.ok(a.app.innerHTML.includes('ui01-secondary-nav'));
assert.ok(a.app.innerHTML.includes('Système'));
assert.ok(a.app.innerHTML.includes('BUREAU'));
const saved=a.run('JSON.stringify(S)');
const savedText=a.store['bdt-v1'];
a.run('nav("team");squadTab="sheet";render()');
assert.ok(a.app.innerHTML.includes('Feuille à 23'));
assert.ok(a.app.innerHTML.includes('Le XV de départ'));
assert.equal(a.run('S.lineup.length'),15);
assert.equal(a.run('S.reserves.length'),8);
a.run('nav("tactics")');
assert.ok(a.app.innerHTML.includes('Plan d’attaque'));
assert.ok(a.app.innerHTML.includes('Centre de match'));
a.run('ui01SetTheme("tribune")');
assert.equal(rootAttrs['data-cd-theme'],'tribune');
assert.equal(a.store['cd-ui-theme-v1'],'tribune');
dark=false;change();
assert.equal(rootAttrs['data-cd-theme'],'tribune','forced theme ignores OS');
a.run('ui01SetTheme("system")');
assert.equal(rootAttrs['data-cd-theme'],'tribune');
dark=true;change();
assert.equal(rootAttrs['data-cd-theme'],'analyste','system follows OS changes');
assert.equal(a.run('ui01SetTheme("invalid")'),false);
assert.equal(a.run('ui01Pref'),'system');
assert.equal(a.run('JSON.stringify(S)'),saved,'UI settings must not mutate career');
assert.equal(a.store['bdt-v1'],savedText,'theme must not write a career save');
a.run('nav("match");beginMatch();pauseMatch();render()');
assert.ok(a.app.innerHTML.includes('live-layout'));
assert.ok(a.app.innerHTML.includes('v40-cockpit'));
assert.ok(!a.app.innerHTML.includes('ui01-appbar'),'preserve V40 live controls');
const b=context();
b.ctx.localStorage.setItem=()=>{throw Error('Storage blocked')};
vm.runInContext(moduleText,b.ctx);
assert.equal(b.run('ui01SetTheme("analyste")'),true,'blocked preference storage must not crash gameplay');
assert.equal(b.run('ui01ResolvedTheme()'),'analyste');
console.log(JSON.stringify({passed:true,checks:['14 routes','FM27 header and responsive','23-player sheet','tactics','auto+manual themes','OS change','storage isolation','V40 live','storage denial']}));
