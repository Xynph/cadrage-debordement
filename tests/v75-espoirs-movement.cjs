'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
for(const file of ['youth-pathways-v72.js','espoirs-league-v73.js','espoirs-accession-v74.js','espoirs-movement-v75.js'])
  vm.runInContext(fs.readFileSync(__dirname+'/../dist/'+file,'utf8'),t.ctx);
for(const name of ['CDEspoirsV73','CDEspoirsAccessionV74','CDEspoirsMovementV75'])
  assert.equal(run(name+'.install(globalThis)'),true,name+' install');
run('start(0)');
assert.equal(run('CDEspoirsMovementV75.valid(S.v75Movement)'),true);
assert.equal(run('S.v75Movement.elite.length'),24);
assert.equal(run('S.v75Movement.accession.length'),20);
assert.equal(run('new Set([...S.v75Movement.elite,...S.v75Movement.accession]).size'),44);
assert.equal(run('S.v73Espoirs.groups.length'),4);
assert.equal(run('S.v74Accession.centers.length'),20);
const season=run('S.season');
run('S.phase="ended";S.round=26;CDEspoirsV73.advance(S);CDEspoirsAccessionV74.advance(S)');
assert.equal(run('S.v73Espoirs.results.length'),202);
assert.equal(run('S.v74Accession.results.length'),187);
assert.equal(run('S.v74Accession.finalists.length'),2);
const choice=run('JSON.parse(JSON.stringify(CDEspoirsMovementV75.candidates(S)))');
assert.equal(choice.promoted.length,2);
assert.equal(choice.relegated.length,2);
const oldPlayers=run('JSON.parse(JSON.stringify(S.v74Accession.centers[CDEspoirsMovementV75.candidates(S).promoted[0]].players.map(p=>p.id)))');
const shot=run('JSON.parse(JSON.stringify(CDEspoirsMovementV75.snapshot(S,CDEspoirsMovementV75.candidates(S))))');
console.log('V75 DIAG pre',JSON.stringify({installed:run('advanceSeason.__v75'),shots:shot&&[shot.elite.map(x=>x.players.length),shot.acc.map(x=>x.players.length)],choice}));
run('advanceSeason()');
console.log('V75 DIAG post',JSON.stringify({season:run('S.season'),movementSeason:run('S.v75Movement.season'),history:run('S.v75Movement.history.length'),installed:run('advanceSeason.__v75')}));
assert.equal(run('S.season'),season+1);
assert.equal(run('S.v75Movement.history.length'),1);
assert.equal(run('S.v75Movement.history[0].season'),season);
assert.equal(run('S.v75Movement.season'),season+1);
assert.equal(run('new Set([...S.v75Movement.elite,...S.v75Movement.accession]).size'),44);
for(let i=0;i<2;i++){
 const a=choice.promoted[i],e=choice.relegated[i];
 assert.equal(run('S.v75Movement.elite['+e+']'),'accession:'+a);
 assert.equal(run('S.v75Movement.accession['+a+']'),'elite:'+e);
 assert.equal(run('CDEspoirsV73.clubPlayers(S,'+e+').length'),22);
 assert.equal(run('CDEspoirsV73.chosen(S,'+e+').every((p,i)=>p&&p.pos===POS[i])'),true,'correct Elite positions after promotion');
 assert.equal(run('S.v74Accession.centers['+a+'].players.length')>=15,true);
 assert.equal(run('CDEspoirsV73.clubName(S,'+e+').length>0'),true);
 assert.equal(run('S.v73Espoirs.fixtures.every(r=>r.every(p=>p.every(id=>id>=0&&id<24)))'),true);
 assert.equal(run('S.v74Accession.fixtures.every(r=>r.every(p=>p.every(id=>id>=0&&id<20)))'),true);
}
assert.equal(run('CDEspoirsV73.clubPlayers(S,'+choice.relegated[0]+').some(p=>p.id==='+JSON.stringify(oldPlayers[0])+')'),true,'promoted youth retained');
assert.equal(run('JSON.stringify(createSaveDocument()).length<5*1024*1024'),true,'export budget');
assert.equal(run('CDEspoirsMovementV75.valid(parseSaveDocument(JSON.stringify(createSaveDocument())).state.v75Movement)'),true,'save roundtrip');
assert.equal(run('CDEspoirsMovementV75.transfer(S,{season:'+season+',promoted:[1,2],relegated:[1,2]},{} )'),false,'no repeat transition');
run('for(let i=0;i<3;i++){S.phase="ended";S.round=26;advanceSeason()}');
assert.equal(run('S.v75Movement.history.length'),4,'four transitions');
assert.equal(run('new Set([...S.v75Movement.elite,...S.v75Movement.accession]).size'),44,'no duplicates after 4 seasons');
assert.equal(run('S.v75Movement.history.every(h=>h.swaps.length===2)'),true);
assert.equal(run('S.v73Espoirs.season===S.season&&S.v74Accession.season===S.season'),true);
assert.equal(run('CDEspoirsMovementV75.ensure({season:3,v75Movement:{broken:true}})'),null,'malformed movement rejected');
const a=run('JSON.parse(JSON.stringify(S))');
delete a.v75Movement;
assert.equal(run('CDEspoirsMovementV75.ensure('+JSON.stringify(a)+').elite.length'),24,'legacy save without V75');
console.log('V75 PASS: 2 promoted/2 relegated, 44 identities, real rosters, fixtures, four seasons, saves');
