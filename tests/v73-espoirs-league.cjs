'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
vm.runInContext(fs.readFileSync(__dirname+'/../dist/youth-pathways-v72.js','utf8'),t.ctx);
vm.runInContext(fs.readFileSync(__dirname+'/../dist/espoirs-league-v73.js','utf8'),t.ctx);
assert.equal(run('CDEspoirsV73.install(globalThis)'),true);
run('start(0)');
assert.equal(run('S.development.academy.length'),15);
assert.equal(run('CDEspoirsV73.setup(S).groups.length'),4);
assert.equal(run('S.v73Espoirs.groups.every(g=>g.length===6)'),true,'4 poules de six');
assert.equal(run('S.v73Espoirs.guests.length'),10,'dix centres issus du vivier PRO D2');
assert.equal(run('S.v73Espoirs.guests.every(g=>g.players.length===15)'),true);
assert.equal(run('S.v73Espoirs.fixtures.length'),10,'10 journées initiales');
assert.equal(run('S.v73Espoirs.fixtures.every(r=>r.length===12)'),true,'12 affiches par journée');
assert.equal(run('new Set(S.v73Espoirs.fixtures.flat().map(x=>x.join("-"))).size'),120,'aucune affiche dupliquee');
assert.equal(run('CDEspoirsV73.setMode(S,"developpement",()=>true)'),true);
const youth=run('S.development.academy[0].id');
assert.equal(run('CDEspoirsV73.setPlayer(S,0,'+JSON.stringify(youth)+',()=>true)'),true);
assert.equal(run('CDEspoirsV73.setPlayer(S,0,"nonexistent",()=>true)'),false);
assert.ok(run('CDEspoirsV73.panel(S).includes("Reichel Espoirs")'));
assert.equal(run('CDEspoirsV73.advance(S)'),true);
assert.equal(run('S.v73Espoirs.round'),0,'aucun match avant fin de journee');
run('S.round=10; CDEspoirsV73.advance(S)');
assert.equal(run('S.v73Espoirs.round'),10,'dix journees');
assert.equal(run('S.v73Espoirs.results.length'),120);
run('S.round=16; CDEspoirsV73.advance(S)');
assert.equal(run('S.v73Espoirs.groups.length'),6,'4 poules de qualification et deux de challenge');
assert.equal(run('new Set(S.v73Espoirs.groups.flat()).size'),24,'les 24 clubs sont repartis une seule fois');
assert.equal(run('S.v73Espoirs.results.length'),192,'qualification et challenge aller retour');
assert.equal(run('S.v73Espoirs.fixtures.slice(10,16).every(r=>r.length===12)'),true);
run('S.round=26; S.phase="ended"; CDEspoirsV73.advance(S)');
assert.equal(run('S.v73Espoirs.round'),26);
assert.equal(run('S.v73Espoirs.results.filter(x=>x.phase==="quarts").length'),4);
assert.equal(run('S.v73Espoirs.results.filter(x=>x.phase==="demi-finales").length'),2);
assert.equal(run('S.v73Espoirs.results.filter(x=>x.phase==="finale").length'),1);
assert.equal(run('S.v73Espoirs.results.filter(x=>x.phase==="challenge-demi").length'),2);
assert.equal(run('S.v73Espoirs.results.filter(x=>x.phase==="challenge-finale").length'),1);
assert.equal(run('Number.isInteger(S.v73Espoirs.champion)'),true);
assert.equal(run('Number.isInteger(S.v73Espoirs.challenge)'),true);
assert.equal(run('CDEspoirsV73.read(S).minutes&&Object.values(S.v73Espoirs.minutes).some(x=>x>=80)'),true);
assert.equal(run('JSON.stringify(createSaveDocument()).length<5*1024*1024'),true,'export sous 5 Mo');
assert.equal(run('parseSaveDocument(JSON.stringify(createSaveDocument())).state.v73Espoirs.results.length'),202,'export/import complet');
run('CDEspoirsV73.closeSeason(S)');
assert.equal(run('S.v73Espoirs.history.length'),1);
run('for(let i=0;i<3;i++){rollDevelopmentYear();S.season++;S.round=0;S.phase="league";beginDevelopmentSeason();CDEspoirsV73.setup(S);S.round=26;CDEspoirsV73.advance(S);CDEspoirsV73.closeSeason(S)}');
assert.equal(run('S.v73Espoirs.history.length'),4,'quatre saisons archivees');
assert.equal(run('parseSaveDocument(JSON.stringify(createSaveDocument())).state.v73Espoirs.history.length'),4);
run('delete S.v73Espoirs');
assert.equal(run('parseSaveDocument(JSON.stringify(createSaveDocument())).state.v73Espoirs===undefined'),true,'ancienne sauvegarde compatible');
console.log('V73 PASS: 24 clubs, 4x6, 10+6 journées, quarts, demies, finale, challenge, 4 saisons et sauvegardes');
