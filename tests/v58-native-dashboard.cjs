'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('dist/manager-mobility.js','utf8');
const start=source.indexOf('function managerMobilityPanel(){');
assert.ok(start>=0);
const section=source.slice(start);
assert.match(section,/Suivi de vos candidatures/);
assert.match(section,/thisSeason\.filter\(a=>a\.status===s\)/);
assert.match(section,/managerMobilityWindow\(\)/);
assert.match(section,/visualEscape\(S\.clubs\[m\.pending\.toClub\]\.name\)/);
const ctx={S:{season:3,club:0,clubs:[{name:'Club A'},{name:'Club B'}],managerMobility:{applications:[{season:3,status:'offered'},{season:3,status:'rejected'},{season:2,status:'offered'}],pending:null,history:[]}},managerMobilityActive:()=>true,managerMobilityWindow:()=>false,visualEscape:s=>s,CDCoachOpportunities:{snapshot:()=>[]}};
vm.runInNewContext(section+';globalThis.panelResult=managerMobilityPanel()',ctx,{timeout:2000});
assert.match(ctx.panelResult,/2 candidature\(s\)/);
assert.match(ctx.panelResult,/1 offre\(s\) à examiner/);
assert.match(ctx.panelResult,/1 refus/);
assert.doesNotMatch(ctx.panelResult,/3 candidature\(s\)/);
assert.equal(ctx.S.managerMobility.applications.length,3);
