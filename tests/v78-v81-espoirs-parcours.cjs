'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {context}=require('./harness.cjs'),t=context(),run=t.run;
for(const name of ['youth-pathways-v72.js','espoirs-league-v73.js','espoirs-accession-v74.js',
 'espoirs-movement-v75.js','espoirs-scouting-v76.js','espoirs-pro-v77.js','espoirs-parcours-v78-v81.js'])
 vm.runInContext(fs.readFileSync(__dirname+'/../dist/'+name,'utf8'),t.ctx);
for(const name of ['CDEspoirsV73','CDEspoirsAccessionV74','CDEspoirsMovementV75',
 'CDEspoirsScoutingV76','CDEspoirsProV77','CDEspoirsPathwaysV78V81'])
 assert.equal(run(name+'.install(globalThis)'),true,name);
run('start(0)');
const api='CDEspoirsPathwaysV78V81',s='S';
assert.equal(run(api+'.valid('+s+'.v78to81)'),true);
const youth=run('S.development.academy[0].id');
const beforeCash=run('S.clubs[S.club].cash');
assert.equal(run(api+'.contract(S,'+JSON.stringify(youth)+',2,()=>false)'),false,'contract rollback');
assert.equal(run('S.clubs[S.club].cash'),beforeCash,'refund');
assert.equal(run(api+'.contract(S,'+JSON.stringify(youth)+',2,()=>true)'),true,'engage youth');
assert.equal(run('S.v78to81.contracts.length'),1);
assert.equal(run(api+'.contract(S,'+JSON.stringify(youth)+',2,()=>true)'),false,'no duplicate');
assert.equal(run('S.development.academy.find(p=>p.id==='+JSON.stringify(youth)+').contractEnd==null'),true,'academy stays academy');
assert.equal(run(api+'.upgrade(S,"facilities",()=>false)'),false,'facility rollback');
assert.equal(run('S.v78to81.facilities'),0);
assert.equal(run(api+'.upgrade(S,"facilities",()=>true)'),true,'upgrade facilities');
assert.equal(run(api+'.upgrade(S,"coaches",()=>true)'),true,'hire coaches');
assert.equal(run('S.v78to81.facilities+S.v78to81.coaches'),2);
const u20=run('S.development.academy.find(p=>p.age<=20&&p.dev.potential>p.rating).id');
const level=run('S.development.academy.find(p=>p.id==='+JSON.stringify(u20)+').rating');
assert.equal(run(api+'.u20(S,'+JSON.stringify(u20)+',()=>false)'),false,'u20 rollback');
assert.equal(run('S.development.academy.find(p=>p.id==='+JSON.stringify(u20)+').rating'),level);
assert.equal(run(api+'.u20(S,'+JSON.stringify(u20)+',()=>true)'),true,'u20 camp');
assert.equal(run('S.development.academy.find(p=>p.id==='+JSON.stringify(u20)+').rating')>level,true,'player progresses');
assert.equal(run(api+'.u20(S,'+JSON.stringify(u20)+',()=>true)'),false,'camp once');
const promote=run('S.development.academy[0].id');
assert.equal(run('CDEspoirsProV77.promote(S,'+JSON.stringify(promote)+',2,()=>true)'),true);
const origin=run('S.clubs[S.club].players.length');
const loanTo=1;
assert.equal(run(api+'.loan(S,'+JSON.stringify(promote)+','+loanTo+',()=>false)'),false,'loan rollback');
assert.equal(run('S.clubs[S.club].players.length'),origin);
assert.equal(run(api+'.loan(S,'+JSON.stringify(promote)+','+loanTo+',()=>true)'),true,'real loan');
assert.equal(run('S.clubs[S.club].players.some(p=>p.id==='+JSON.stringify(promote)+')'),false,'departing pro');
assert.equal(run('S.clubs['+loanTo+'].players.some(p=>p.id==='+JSON.stringify(promote)+')'),true,'other club has player');
assert.equal(run(api+'.loan(S,'+JSON.stringify(promote)+','+loanTo+',()=>true)'),false,'no duplicated loan');
assert.equal(run('JSON.parse(JSON.stringify(parseSaveDocument(JSON.stringify(createSaveDocument())).state.v78to81)).loans.length'),1,'save roundtrip loan');
assert.equal(run('JSON.stringify(createSaveDocument()).length<5*1024*1024'),true,'save size');
run('S.phase="ended";S.round=26;advanceSeason()');
assert.equal(run('S.v78to81.loans.length'),0,'annual loan reset');
assert.equal(run('S.clubs[S.club].players.some(p=>p.id==='+JSON.stringify(promote)+')'),true,'real loan return');
assert.equal(run('S.clubs['+loanTo+'].players.some(p=>p.id==='+JSON.stringify(promote)+')'),false,'borrower released player');
assert.equal(run('S.v78to81.history[0].loans.length'),1,'loan history');
assert.equal(run('S.v78to81.u20.length'),0,'u20 annual reset');
run('for(let i=0;i<4;i++){S.phase="ended";S.round=26;advanceSeason()}');
assert.equal(run('S.v78to81.history.length'),4,'history limited');
assert.equal(run(api+'.valid(S.v78to81)'),true,'multi-season');
const legacy=run('JSON.parse(JSON.stringify(S))');delete legacy.v78to81;
assert.equal(run(api+'.valid('+api+'.ensure('+JSON.stringify(legacy)+'))'),true,'legacy save compatible');
console.log('V78-V81 PASS: loans and returns, engagements, U20 camps, academy investment, rollback, 5 seasons, saves');
