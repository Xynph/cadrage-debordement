'use strict';
const assert=require('node:assert/strict');
const {context,engineContext}=require('./harness.cjs');
const t=context();let run=t.run;
run('start(0)');
const before=run('JSON.stringify(S)');
const a=run('managerSeasonSnapshot()');
assert.ok(a.professionals>0&&a.professionals<=run('professionalCapacity()'),'effectif réel');
assert.equal(a.available,run('professionalCapacity()-professionalLoanReservations().length')-a.professionals,'places calculées');
assert.equal(a.academy,run('S.development.academy.length'),'espoirs natifs');
assert.equal(a.weeklyPayroll,run('club().players.reduce((s,p)=>s+p.salary,0)'),'masse salariale native');
assert.ok(run('JSON.stringify(S)')===before,'pas de mutation de la carrière lors du modèle');
const html=run('managerSeasonPanel()');
assert.match(html,/Piloter votre saison/);
assert.match(html,/Suivre la relève/);
assert.match(html,/Explorer le recrutement/);
assert.match(html,/officeAction\('market',null,'contracts'\)/);
assert.ok(run('JSON.stringify(S)')===before,'rendu sans mutation de la carrière');
run('nav("dashboard")');
assert.match(t.app.innerHTML,/Pilotage de saison/,'panneau réellement présent au bureau');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde préservée');
// L’écran précédent est reçu dans le vrai HTML ; la progression ne teste que le modèle.
const engine=engineContext(t.state());engine.setSeed(t.seed());assert.ok(engine.run('JSON.stringify(S)')===run('JSON.stringify(S)'),'reprise de la fixture de pilotage sans mutation');t.close();run=engine.run;
engine.deferSaves();engine.week(23);run('club().cash=-100;club().players[0].contractEnd=S.season;club().players[1].injury=3');
const stressed=run('managerSeasonSnapshot()');
assert.ok(stressed.priorities.some(x=>x.id==='cash'&&x.weight===98));
assert.ok(stressed.priorities.some(x=>x.id==='expiring'&&x.weight===95));
assert.ok(stressed.priorities.some(x=>x.id==='injured'));
assert.ok(stressed.priorities.findIndex(x=>x.id==='cash')<stressed.priorities.findIndex(x=>x.id==='expiring'),'le risque financier précède les contrats tout en conservant la priorité absolue à la feuille');
assert.ok(stressed.priorities.every((x,i,items)=>i===0||items[i-1].weight>=x.weight),'priorités triées par urgence sans supprimer les alertes métier');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde compatible après modifications métier valides');
engine.season();run('S.manager.missions=[];S.manager.reports=[]');
const ended=run('managerSeasonSnapshot()');
assert.ok(!ended.priorities.some(x=>x.id==='scout'),'pas de mission suggérée en fin de saison');
engine.close();console.log('manager-season-pilotage: PASS (priorités, économie, contrats, blessures, formation, rendu, sauvegarde)');
