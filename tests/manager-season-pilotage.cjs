'use strict';
const assert=require('node:assert/strict');
const {context}=require('./harness.cjs');
const t=context(),run=t.run;
run('start(0)');
const before=run('JSON.stringify(S)');
const a=run('managerSeasonSnapshot()');
assert.ok(a.professionals>0&&a.professionals<=42,'effectif réel');
assert.equal(a.available,42-a.professionals,'places calculées');
assert.equal(a.academy,run('S.development.academy.length'),'espoirs natifs');
assert.equal(a.weeklyPayroll,run('club().players.reduce((s,p)=>s+p.salary,0)'),'masse salariale native');
assert.equal(run('JSON.stringify(S)'),before,'pas de mutation de la carrière lors du modèle');
const html=run('managerSeasonPanel()');
assert.match(html,/Piloter votre saison/);
assert.match(html,/Suivre la relève/);
assert.match(html,/Explorer le recrutement/);
assert.match(html,/officeAction\('market',null,'contracts'\)/);
assert.equal(run('JSON.stringify(S)'),before,'rendu sans mutation de la carrière');
run('nav("dashboard")');
assert.match(t.app.innerHTML,/Pilotage de saison/,'panneau réellement présent au bureau');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde préservée');
run('S.round=23;club().cash=-100;club().players[0].contractEnd=S.season;club().players[1].injury=3');
const stressed=run('managerSeasonSnapshot()');
assert.ok(stressed.priorities.some(x=>x.id==='cash'&&x.weight===98));
assert.ok(stressed.priorities.some(x=>x.id==='expiring'&&x.weight===95));
assert.ok(stressed.priorities.some(x=>x.id==='injured'));
assert.equal(stressed.priorities[0].id,'cash','risque financier remonté');
assert.equal(stressed.priorities[1].id,'expiring','contrat urgent remonté');
assert.ok(run('!!parseSaveDocument(JSON.stringify(createSaveDocument()))'),'sauvegarde compatible après modifications métier valides');
run('S.phase="ended";S.manager.missions=[];S.manager.reports=[]');
const ended=run('managerSeasonSnapshot()');
assert.ok(!ended.priorities.some(x=>x.id==='scout'),'pas de mission suggérée en fin de saison');
console.log('manager-season-pilotage: PASS (priorités, économie, contrats, blessures, formation, rendu, sauvegarde)');
